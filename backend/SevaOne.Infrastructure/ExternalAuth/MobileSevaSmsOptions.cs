namespace SevaOne.Infrastructure.ExternalAuth;

/// <summary>
/// Karnataka's Mobile Seva SMS gateway (smsmobile1.karnataka.gov.in) -- department-registered
/// OTP text sending. Leave Username empty to keep using LoggedSmsOtpSender (see
/// DependencyInjection.AddSevaOneInfrastructure); only real environments should set these.
/// </summary>
public sealed class MobileSevaSmsOptions
{
    public const string SectionName = "MobileSevaSms";

    public string BaseUrl { get; set; } = "http://smsmobile1.karnataka.gov.in/index.php/sendmsg";

    /// <summary>Department login username issued by Mobile Seva. Leave empty until onboarded; the real sender won't be registered.</summary>
    public string Username { get; set; } = string.Empty;

    /// <summary>Department login password. Sent MD5-hashed, never in plaintext. Store via secret/.env, never commit a real value.</summary>
    public string Password { get; set; } = string.Empty;

    /// <summary>Department-allocated sender ID (e.g. "MOBKAR").</summary>
    public string SenderId { get; set; } = string.Empty;

    /// <summary>Department key generated by logging in to the Mobile Seva services portal -- one of the four inputs to the request-signing hash.</summary>
    public string SecureKey { get; set; } = string.Empty;

    /// <summary>Template ID registered for the OTP message content below -- must match exactly, including the {#num#} placeholder position.</summary>
    public string TemplateId { get; set; } = string.Empty;

    /// <summary>OTP message template; {#num#} is replaced with the actual OTP before sending.</summary>
    public string MessageTemplate { get; set; } = "Your OTP is {#num#}.-Seva One,Gok";
}
